#!/usr/bin/env node
/**
 * Generates the case index at the top of `test-cases/README.md`: manual cases first (what a
 * person must run by hand), then the planned backlog and counts per status.
 *
 * The index is generated, never hand-edited, so it cannot go stale: `pnpm tc:check` fails when the
 * README differs from what this script would write.
 *
 * Usage:
 *   pnpm tc:index        # rewrite the index in test-cases/README.md
 *
 * See docs/test-case-management.md.
 */
import console from 'node:console';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';
import prettier from 'prettier';
import {
  AUTOMATION_STATUSES,
  CATALOGUE_DIR,
  PRIORITIES,
  REPO_ROOT,
  loadCatalogue,
} from './catalogue.js';

export const README_PATH = path.join(CATALOGUE_DIR, 'README.md');
export const INDEX_START = '<!-- tc-index:start -->';
export const INDEX_END = '<!-- tc-index:end -->';

/** Cases a person runs by hand (no automated test). */
const BY_HAND = ['manual', 'not-automatable'];

/** GitHub heading anchor, e.g. "E2E-AUTO-004: Stop-Loss, close" -> "e2e-auto-004-stop-loss-close". */
export function headingAnchor(text) {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .trim()
    .replace(/\s/g, '-');
}

/** Case file path relative to test-cases/ (`testCase.file` is relative to the repo root). */
const relativeFile = (testCase) =>
  path.relative(CATALOGUE_DIR, path.join(REPO_ROOT, testCase.file)).split(path.sep).join('/');

/** Escapes `|` so a case title cannot break the Markdown table it is placed in. */
export const escapeCell = (text) => String(text).replace(/\|/g, '\\|');

/** Link from README.md to a case's heading in its catalogue file. */
const caseLink = (testCase) =>
  `[${testCase.id}](${relativeFile(testCase)}#${headingAnchor(`${testCase.id}: ${testCase.title}`)})`;

const byPriorityThenId = (a, b) =>
  PRIORITIES.indexOf(a.priority) - PRIORITIES.indexOf(b.priority) || a.id.localeCompare(b.id);

/** Markdown for the generated block (without the start/end markers). */
export function renderCaseIndex(cases) {
  const byHand = cases.filter((c) => BY_HAND.includes(c.automation)).sort(byPriorityThenId);
  const planned = cases
    .filter((c) => c.automation === 'planned')
    .sort((a, b) => relativeFile(a).localeCompare(relativeFile(b)) || a.id.localeCompare(b.id));
  const counts = AUTOMATION_STATUSES.map(
    (status) => `| ${status} | ${cases.filter((c) => c.automation === status).length} |`,
  );

  const lines = [
    '<!-- Generated by `pnpm tc:index` from the catalogue files: do not edit by hand. -->',
    '<!-- `pnpm tc:check` fails when this section is out of date. -->',
    '',
    `## 🖐️ Manual test cases (${byHand.length})`,
    '',
    'These cases have **no automated test**: a person runs them by hand, following the steps and',
    'expected result behind each link. Highest priority first.',
    '',
  ];
  if (byHand.length) {
    lines.push(
      '| ID | Case | Priority | Status | File |',
      '| :-- | :-- | :-- | :-- | :-- |',
      ...byHand.map(
        (c) =>
          `| ${caseLink(c)} | ${escapeCell(c.title)} | ${c.priority} | ${c.automation} | \`${relativeFile(c)}\` |`,
      ),
    );
  } else {
    lines.push('_No manual cases._');
  }

  lines.push(
    '',
    `## 🗺️ Planned cases (${planned.length})`,
    '',
    'Cases with no test yet: the automation backlog. Each one becomes `automated` together with its',
    'test.',
    '',
    '<details>',
    `<summary>Show the ${planned.length} planned cases</summary>`,
    '',
    '| ID | Case | Priority | File |',
    '| :-- | :-- | :-- | :-- |',
    ...planned.map(
      (c) => `| ${caseLink(c)} | ${escapeCell(c.title)} | ${c.priority} | \`${relativeFile(c)}\` |`,
    ),
    '',
    '</details>',
    '',
    '## 📊 Cases by status',
    '',
    '| Status | Cases |',
    '| :-- | --: |',
    ...counts,
    `| **Total** | **${cases.length}** |`,
  );
  return lines.join('\n');
}

/** README content with the index block replaced, formatted with the repo's Prettier config. */
export async function buildReadme(readme, cases) {
  const start = readme.indexOf(INDEX_START);
  const end = readme.indexOf(INDEX_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${README_PATH} must contain ${INDEX_START} and ${INDEX_END} markers`);
  }
  const updated = `${readme.slice(0, start + INDEX_START.length)}\n\n${renderCaseIndex(cases)}\n\n${readme.slice(end)}`;
  const options = (await prettier.resolveConfig(README_PATH)) ?? {};
  return prettier.format(updated, { ...options, filepath: README_PATH });
}

/** True when README.md already contains the index for the current catalogue. */
export async function isIndexUpToDate(cases) {
  const readme = fs.readFileSync(README_PATH, 'utf-8');
  return readme === (await buildReadme(readme, cases));
}

async function main() {
  const { cases, errors } = loadCatalogue();
  if (errors.length) {
    console.error(`❌ Fix the catalogue first (pnpm tc:check):\n${errors.join('\n')}`);
    process.exit(1);
  }
  const readme = fs.readFileSync(README_PATH, 'utf-8');
  fs.writeFileSync(README_PATH, await buildReadme(readme, cases));
  console.log(`✅ Updated ${path.relative(process.cwd(), README_PATH)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(`❌ tc:index failed: ${error.message}`);
    process.exit(1);
  });
}
